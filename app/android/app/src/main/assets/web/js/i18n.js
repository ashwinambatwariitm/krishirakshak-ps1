const SUPPORTED_LANGS = ["en", "hi", "mr", "te", "ta", "kn", "bn", "gu", "pa", "or"];
let currentLanguage = window.CONFIG ? (window.CONFIG.DEFAULT_LANG || "en") : "en";
if (!SUPPORTED_LANGS.includes(currentLanguage)) currentLanguage = "en";

function setLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = "en";
  currentLanguage = lang;
  localStorage.setItem("KR_LANG", lang);
  if (window.CONFIG) {
    window.CONFIG.DEFAULT_LANG = lang;
    window.CONFIG.TRANSLATE_LANG = lang === "en" ? "" : lang;
    localStorage.setItem("KR_TRANSLATE", window.CONFIG.TRANSLATE_LANG);
  }
  updateStaticDOMText();
  document.documentElement.lang = lang;
  
  // Sync all header and page dropdowns
  const headerSelect = document.getElementById("header-lang-select");
  if (headerSelect && headerSelect.value !== lang) {
    headerSelect.value = lang;
  }
  const pageSelect = document.getElementById("select-translate");
  if (pageSelect) {
    pageSelect.value = lang === "en" ? "" : lang;
  }

  window.dispatchEvent(new CustomEvent("kr-lang-changed", { detail: { lang } }));
}

function getLanguage() {
  return currentLanguage;
}

function t(key) {
  const dict = I18N[currentLanguage] || I18N.hi || I18N.en;
  return dict[key] || I18N.en[key] || key;
}

function updateStaticDOMText() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      el.textContent = t(key);
    }
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.getAttribute("data-i18n-ph");
    if (key) {
      el.setAttribute("placeholder", t(key));
    }
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const key = el.getAttribute("data-i18n-title");
    if (key) {
      el.setAttribute("title", t(key));
    }
  });
}

window.I18N = I18N;
window.t = t;
window.setLanguage = setLanguage;
window.getLanguage = getLanguage;
window.updateStaticDOMText = updateStaticDOMText;
window.SUPPORTED_LANGS = SUPPORTED_LANGS;
