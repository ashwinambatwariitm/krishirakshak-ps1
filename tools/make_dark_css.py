"""Generate app/web/css/dark.css (night mode of the farmer app) from app/web/css/style.css.

The app's stylesheet has the theme colours as variables, but also about a hundred fixed colours (white cards, light
green / red / amber boxes, dark text). Night mode therefore needs more than new variable values: for every rule that
sets a fixed colour, this script writes the same rule under html[data-theme="dark"] with a night colour of the same
hue:
  - light backgrounds and borders become dark (white card -> dark green-grey, light red box -> dark red box),
  - dark text becomes light, strong colours (red badge, green button) stay as they are.
The variables are set in the hand-written block at the top of the output. Rerun after changing style.css:

    python tools/make_dark_css.py
"""
import colorsys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "app" / "web" / "css" / "style.css"
OUT = ROOT / "app" / "web" / "css" / "dark.css"
PREFIX = 'html[data-theme="dark"]'

# Night values of the theme variables (style.css :root; the older names there refer to these)
VARIABLES = """  --brand: #22a052;
  --brand-deep: #a5d6a7;
  --brand-tint: #1d3523;
  --header-bg: #0f2c18;
  --bg: #0e140f;
  --surface: #172019;
  --surface-2: #1d271f;
  --line: #2c3a2e;
  --ink: #e7eee5;
  --ink-2: #b9ccb5;
  --ink-3: #8fa18b;
  --danger: #ef5350; --danger-tint: #3a1c1c; --danger-line: #5a2a2a;
  --warn: #ffa040; --warn-tint: #3a2914; --warn-line: #5a4020;
  --info: #9ec3e6; --info-tint: #18232e; --info-line: #2a3a4a;
  --shadow: 0 2px 10px rgba(0, 0, 0, 0.5);
  color-scheme: dark;"""

HEX = re.compile(r"#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")
RGBA = re.compile(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([0-9.]+)\s*)?\)")
# Parts that stay as they are at night: the green header and its buttons, the crop frame over the photo
KEEP = re.compile(r"app-header|icon-btn|brand|header-actions|crop-frame|crop-handle|crop-stage|home-logo")
COLOR_PROPS = ("background", "background-color", "background-image", "color", "border", "border-color",
               "border-top", "border-bottom", "border-left", "border-right", "border-left-color", "outline",
               "fill", "stroke")


def to_rgb(h):
    h = h if len(h) == 6 else "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def night(rgb, role):
    """Night colour for one colour: role is 'bg' (backgrounds, borders) or 'fg' (text, icons)."""
    hue, light, sat = colorsys.rgb_to_hls(*rgb)
    if role == "bg":
        if light < 0.6:                      # strong colour (button, badge): keep
            return rgb
        light = 0.11 + (1 - light) * 0.45    # white -> 0.11, light tint 0.9 -> 0.155
        if sat < 0.05:                       # white / grey: the green-grey of the night cards
            hue, sat = 0.36, 0.15
        sat = min(sat, 0.35)
    else:
        if light > 0.45:                     # already light or strong: keep, a little lighter if needed
            light = max(light, 0.62)
        else:
            light = 0.86 - light * 0.3       # dark text -> light text of the same hue
            sat = min(sat, 0.55)
    return colorsys.hls_to_rgb(hue, light, sat)


def hexs(rgb):
    return "#" + "".join(f"{round(max(0, min(1, c)) * 255):02x}" for c in rgb)


def convert_value(prop, value):
    role = "fg" if prop in ("color", "fill", "stroke") else "bg"
    if prop.startswith("border") or prop == "outline":
        role = "bg"
    out = HEX.sub(lambda m: hexs(night(to_rgb(m.group(1)), role)), value)

    def rgba(m):
        rgb = tuple(int(m.group(i)) / 255 for i in (1, 2, 3))
        n = night(rgb, role)
        r, g, b = (round(c * 255) for c in n)
        return f"rgba({r}, {g}, {b}, {m.group(4)})" if m.group(4) else f"rgb({r}, {g}, {b})"
    return RGBA.sub(rgba, out)


def rules(css):
    """(at-rule or '', selector, body) for each rule; nested one level for @media."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    i = 0
    while True:
        j = css.find("{", i)
        if j == -1:
            return
        sel = css[i:j].strip()
        depth, k = 0, j
        while k < len(css):
            depth += css[k] == "{"
            depth -= css[k] == "}"
            if depth == 0:
                break
            k += 1
        body = css[j + 1:k]
        if sel.startswith("@media"):
            for _, s, b in rules(body):
                yield sel, s, b
        elif not sel.startswith("@") and not sel.startswith(":root"):
            yield "", sel, body
        i = k + 1


def main():
    out = ["/* " + __doc__.strip().split("\n")[0] + " Generated by tools/make_dark_css.py, do not edit by hand. */",
           f"{PREFIX} {{\n{VARIABLES}\n}}", ""]
    count = 0
    for media, sel, body in rules(SRC.read_text()):
        decls = []
        for d in body.split(";"):
            if ":" not in d:
                continue
            prop, value = (x.strip() for x in d.split(":", 1))
            if prop in COLOR_PROPS and (HEX.search(value) or RGBA.search(value)) and "var(" not in value:
                new = convert_value(prop, value)
                if new != value:
                    decls.append(f"  {prop}: {new};")
        if not decls or KEEP.search(sel):
            continue
        selectors = ", ".join(f"{PREFIX} {s.strip()}" for s in sel.split(","))
        block = f"{selectors} {{\n" + "\n".join(decls) + "\n}"
        out.append(f"{media} {{\n{block}\n}}" if media else block)
        count += 1
    # Inline colours in index.html (technical details box, helpline title)
    out.append(f'{PREFIX} #tech-details-json {{ background: #1a221b !important; }}')
    out.append(f'{PREFIX} .helpline-box h3 {{ color: #80cbc4 !important; }}')
    # Active bottom tab: brighter green on the dark bar
    out.append(f'{PREFIX} .nav-item.active {{ color: var(--primary-glow); }}')
    out.append(f'{PREFIX} .nav-item.active svg {{ stroke: var(--primary-glow); }}')
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {count} rules")


if __name__ == "__main__":
    main()
