"""Generate cpp/src/text_tables.hpp: the Unicode character classes and word lists used by the C++ port of the
IndicTrans2 text pre/post-processing (cpp/src/indic_text.cpp).

The Python reference (IndicTransToolkit + sacremoses + indicnlp) uses
  - sacremoses' Perl Unicode property tables (IsN, IsAlnum, IsAlpha, IsLower) plus Indic viramas and nuktas,
  - Python `re` Unicode classes: \\d (decimal digits), \\w (alphanumeric or '_'), \\s (whitespace),
  - the Moses non-breaking prefix list for English.
Exporting the same sets as code-point ranges lets the C++ code classify characters exactly like Python.
The generated header is plain ASCII (code points are written as hex numbers).

Build-time tool only; run with the translation venv:
    python cpp/tools/gen_text_tables.py > cpp/src/text_tables.hpp
"""
import sys
import unicodedata

from sacremoses.corpus import NonbreakingPrefixes, Perluniprops
from sacremoses.indic import NUKTAS, VIRAMAS


def ranges(codepoints):
    """Sorted code points -> list of inclusive (first, last) ranges."""
    out = []
    for cp in sorted(set(codepoints)):
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def emit(name, codepoints, doc):
    rs = ranges(codepoints)
    print(f"// {doc} ({len(set(codepoints))} code points, {len(rs)} ranges)")
    print(f"inline constexpr CodeRange {name}[] = {{")
    line = "   "
    for a, b in rs:
        item = f" {{0x{a:X}, 0x{b:X}}},"
        if len(line) + len(item) > 116:
            print(line)
            line = "   "
        line += item
    print(line)
    print("};\n")


def main():
    p = Perluniprops()
    extra = [ord(c) for c in VIRAMAS + NUKTAS]
    all_cp = range(0x110000)
    print("/*")
    print(" * text_tables.hpp - GENERATED by cpp/tools/gen_text_tables.py, do not edit by hand.")
    print(" *")
    print(" * Character classes and word lists of the Python text processing used with IndicTrans2")
    print(" * (sacremoses Perl Unicode properties, Python re classes, Moses English non-breaking prefixes),")
    print(f" * exported from Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).")
    print(" */")
    print("#pragma once\n")
    print("namespace kr::text_tables {\n")
    print("struct CodeRange {")
    print("    char32_t first;")
    print("    char32_t last;   // inclusive")
    print("};\n")
    emit("kIsN", [ord(c) for c in p.chars("IsN")], "Moses IsN: numbers")
    emit("kIsAlnum", [ord(c) for c in p.chars("IsAlnum")] + extra, "Moses IsAlnum + Indic viramas and nuktas")
    emit("kIsAlpha", [ord(c) for c in p.chars("IsAlpha")] + extra, "Moses IsAlpha + Indic viramas and nuktas")
    emit("kIsLower", [ord(c) for c in p.chars("IsLower")], "Moses IsLower")
    emit("kPyDigit", [c for c in all_cp if unicodedata.category(chr(c)) == "Nd"], "Python re \\d (category Nd)")
    emit("kPyWord", [c for c in all_cp if chr(c).isalnum() or chr(c) == "_"], "Python re \\w (isalnum or '_')")
    emit("kPySpace", [c for c in all_cp if chr(c).isspace()], "Python re \\s / str.split() (isspace)")

    words = [w.strip() for w in NonbreakingPrefixes().words("en")]
    assert all(w.isascii() for w in words)
    print("// Moses English non-breaking prefixes (\" #NUMERIC_ONLY#\" marks prefixes that only stay before a number)")
    print("inline constexpr const char* kEnNonbreakingPrefixes[] = {")
    line = "   "
    for w in words:
        item = ' "' + w.replace("\\", "\\\\").replace('"', '\\"') + '",'
        if len(line) + len(item) > 116:
            print(line)
            line = "   "
        line += item
    print(line)
    print("};\n")
    print("}  // namespace kr::text_tables")


if __name__ == "__main__":
    main()
